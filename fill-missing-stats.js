/* =========================================================================
   FILL + REFRESH — one pass over sf-food-data.js that fixes the two data
   quality gaps without a full regeneration:

     1. FRESHNESS: every spot's rating, review count, and businessStatus is
        re-pulled from the Places API (name+address text search). Closed
        places get flagged so they can be pruned.
     2. COVERAGE: spots with dishApproval == null get the full SerpAPI
        review analysis (reviews-provider dishStats) so "not yet rated"
        disappears. Spots that already have stats are left alone — manual
        verified entries always win.

   Writes sf-food-data.js incrementally (after every spot), so an
   interrupted run keeps its progress. Re-running skips what's done.

       node fill-missing-stats.js            # full run
       node fill-missing-stats.js --dry-run  # report what it would do
   ========================================================================= */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

require("fs").readFileSync(path.join(__dirname, ".env"), "utf8").split("\n")
  .forEach((l) => { const m = l.match(/^([A-Z_]+)=(.*)$/); if (m && !process.env[m[1]]) process.env[m[1]] = m[2]; });

const { reviewsEnabled, dishStats } = require("./reviews-provider.js");
const DISHES = require("./dishes.js");
const KEY = process.env.GOOGLE_PLACES_API_KEY;
const DRY = process.argv.includes("--dry-run");
const DATA_PATH = path.join(__dirname, "sf-food-data.js");

const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(DATA_PATH, "utf8"), ctx);
const FOOD = ctx.window.SF_FOOD_DATA;

function save() {
  FOOD.refreshedAt = new Date().toISOString();
  const out = `/* AUTO-GENERATED by generate-data.js; refreshed by fill-missing-stats.js ${FOOD.refreshedAt}. Do not hand-edit. */\nwindow.SF_FOOD_DATA = ${JSON.stringify(FOOD, null, 1)};\n`;
  fs.writeFileSync(DATA_PATH, out);
}

function keywordsFor(cuisineId, dishId) {
  const d = (DISHES[cuisineId]?.dishes || []).find((x) => x.id === dishId);
  return d ? d.keywords : null;
}

async function placeLookup(spot) {
  const res = await fetch("https://places.googleapis.com/v1/places:searchText", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-Goog-Api-Key": KEY,
      "X-Goog-FieldMask": "places.id,places.displayName,places.rating,places.userRatingCount,places.businessStatus",
    },
    body: JSON.stringify({ textQuery: `${spot.name} ${spot.address || "San Francisco"}`, maxResultCount: 1 }),
  });
  if (!res.ok) throw new Error(`places ${res.status}`);
  const j = await res.json();
  return j.places?.[0] || null;
}

(async () => {
  if (!KEY) { console.error("Missing GOOGLE_PLACES_API_KEY"); process.exit(1); }
  const canReview = reviewsEnabled();
  console.log(`Reviews provider ${canReview ? "ENABLED" : "disabled"} · ${DRY ? "DRY RUN" : "live"}`);

  let refreshed = 0, filled = 0, closed = 0, skippedDone = 0, errors = 0;

  for (const [cuisineId, cuisine] of Object.entries(FOOD.cuisines)) {
    for (const dish of cuisine.dishes) {
      for (const spot of dish.spots) {
        // dishMentions === 0 means the analysis ran and found nothing — that is
        // an answer, not a gap; only null (never analyzed) needs a fill.
        const needsStats = spot.dishApproval == null && spot.dishMentions == null && !spot.dishVerified;
        const already = spot._refreshedAt && !needsStats;
        if (already) { skippedDone++; continue; }
        if (DRY) {
          console.log(`${needsStats ? "FILL " : "fresh"} ${cuisineId}/${dish.id} · ${spot.name}`);
          if (needsStats) filled++; else refreshed++;
          continue;
        }
        try {
          const p = await placeLookup(spot);
          if (p) {
            if (p.rating) spot.rating = p.rating;
            if (p.userRatingCount) spot.reviews = String(p.userRatingCount);
            spot.businessStatus = p.businessStatus || "OPERATIONAL";
            if (spot.businessStatus !== "OPERATIONAL") {
              closed++;
              console.log(`  ⚠ ${spot.name}: ${spot.businessStatus}`);
            }
            if (needsStats && canReview && p.id) {
              const kws = keywordsFor(cuisineId, dish.id);
              if (kws) {
                const stats = await dishStats({ placeId: p.id }, kws);
                if (stats && stats.mentions > 0) {
                  spot.dishMentions = stats.mentions;
                  spot.dishApproval = stats.approval;
                  spot.dishSample = stats.sample;
                  spot.dishSource = stats.source;
                  filled++;
                  console.log(`  ✓ ${spot.name}: ${stats.mentions} mentions, ${stats.approval}% (read ${stats.totalRead})`);
                } else if (stats) {
                  spot.dishMentions = 0;
                  spot.dishSource = stats.source;
                  console.log(`  · ${spot.name}: 0 mentions in ${stats.totalRead} reviews`);
                }
              }
            }
          } else {
            console.log(`  ? ${spot.name}: no Places match`);
          }
          spot._refreshedAt = new Date().toISOString().slice(0, 10);
          refreshed++;
          save();
        } catch (e) {
          errors++;
          console.log(`  ✗ ${spot.name}: ${e.message}`);
          if (/serpapi 4|account/i.test(e.message)) { console.log("Stopping review fills (provider error); refresh continues."); }
        }
      }
    }
  }
  if (!DRY) save();
  console.log(`\nDone. refreshed=${refreshed} statsFilled=${filled} closedFlagged=${closed} skipped=${skippedDone} errors=${errors}`);
})();
